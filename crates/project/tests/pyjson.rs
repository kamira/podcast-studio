#[test]
fn float_roundtrip_parsing_matches_python() {
    let mut failures = Vec::new();
    for &(text, bits) in PARSE_HARD {
        let v: Value = serde_json::from_str(text).expect("可解析");
        let got = v.as_f64().expect("數值").to_bits();
        if got != bits {
            failures.push(format!("{text}:預期 {bits:#018x},得到 {got:#018x}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn parsed_python_reprs_round_trip_through_the_writer() {
    // Python 寫出的浮點原文 → Rust 解析 → Rust 寫出,與原文相同
    for &(bits, text) in FLOAT_REPR {
        let v: Value = serde_json::from_str(text).expect("可解析");
        assert_eq!(v.as_f64().map(f64::to_bits), Some(bits), "{text}");
        assert_eq!(dumps_sorted(&v), text);
    }
}
