#[test]
fn float_repr_matches_python_repr() {
    assert_eq!(FLOAT_REPR.len(), 160);
    let mut failures = Vec::new();
    for &(bits, want) in FLOAT_REPR {
        let got = float_repr(f64::from_bits(bits));
        if got != want {
            failures.push(format!("{bits:#018x}:預期 {want},得到 {got}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn float_repr_exponent_boundaries() {
    // 十進位指數 < −4 或 ≥ 16 改科學記號;指數帶正負號且至少兩位;整數值浮點補 .0
    for (v, want) in [
        (1e16, "1e+16"),
        (1e15, "1000000000000000.0"),
        (9999999999999998.0, "9999999999999998.0"),
        (1e-5, "1e-05"),
        (1e-4, "0.0001"),
        (1.5e-7, "1.5e-07"),
        (-0.0, "-0.0"),
        (0.0, "0.0"),
        (2.0, "2.0"),
        (1e100, "1e+100"),
        (1.7976931348623157e308, "1.7976931348623157e+308"),
        (5e-324, "5e-324"),
    ] {
        assert_eq!(float_repr(v), want, "{v:e}");
    }
}

