#[test]
fn dump_floats_use_python_repr() {
    for &(bits, want) in FLOAT_REPR {
        let v = f64::from_bits(bits);
        assert_eq!(dump(&v), format!("{want}\n"), "{bits:#018x}");
        assert_eq!(dumps_sorted(&v), want, "{bits:#018x}");
    }
}

